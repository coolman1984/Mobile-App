def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("'", "\\'").replace("<", "&lt;")

def write_xml(path: Path, lang: str):
    lines = ['<?xml version="1.0" encoding="utf-8"?>', "<resources>"]
    for key, ar, en in ENTRIES:
        text = ar if lang == "ar" else en
        lines.append(f'    <string name="{key}">{esc(text)}</string>')
    # plurals
    by_name = {}
    for name, qty, ar, en in PLURALS:
        text = ar if lang == "ar" else en
        if text is None:
            continue
        by_name.setdefault(name, []).append((qty, text))
    for name, items in by_name.items():
        lines.append(f'    <plurals name="{name}">')
        for qty, text in items:
            lines.append(f'        <item quantity="{qty}">{esc(text)}</item>')
        lines.append("    </plurals>")
    lines.append("</resources>")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")

